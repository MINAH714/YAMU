    user_id BIGINT NOT NULL COMMENT '원결제 사용자; 청구서 일치 검증용',
    user_card_id BIGINT NOT NULL COMMENT '원결제 카드; 청구서 일치 검증용',
    card_bill_id BIGINT NULL COMMENT '배정 청구서; 배정 전 NULL',
    installment_no SMALLINT NOT NULL COMMENT '일시불 1, 할부 1부터 시작',
    billing_month DATE NOT NULL COMMENT '예정 청구 월의 1일',
    principal_amount BIGINT NOT NULL COMMENT '회차 원금; 나머지는 마지막 회차',
    fee_amount BIGINT NULL COMMENT '회차 수수료; 미산정 NULL, 무이자 확정 0',
    billed_amount BIGINT NULL COMMENT '원금+확정 수수료; 미산정 NULL',
    annual_fee_rate DECIMAL(9,6) NULL COMMENT '적용 연 수수료율 스냅샷; 0~1',
    fee_calculation_snapshot JSON NULL COMMENT '카드사 수수료 계산 근거·기간·반올림',
    status VARCHAR(24) NOT NULL COMMENT '회차 청구·출금·제외 상태 코드',
    unpaid_principal_waived_at TIMESTAMP(6) NULL COMMENT 'UTC 취소로 미납 원금 제외한 시각',
    PRIMARY KEY (bill_item_id),
    UNIQUE KEY uk_bill_item_installment (payment_transaction_id, installment_no),
    UNIQUE KEY uk_item_payment_owner (bill_item_id, payment_transaction_id, user_id),
    KEY ix_item_payment_card_owner (payment_transaction_id, user_id, user_card_id),
    KEY ix_item_bill_card_owner (card_bill_id, user_id, user_card_id),
    KEY ix_item_pending_month (user_card_id, billing_month, status),
    CONSTRAINT fk_item_payment_owner FOREIGN KEY (payment_transaction_id, user_id, user_card_id) REFERENCES payment_transaction (payment_transaction_id, user_id, user_card_id),
    CONSTRAINT fk_item_bill_owner FOREIGN KEY (card_bill_id, user_id, user_card_id) REFERENCES card_bill (card_bill_id, user_id, user_card_id),
    CONSTRAINT ck_item_installment CHECK (installment_no > 0),
    CONSTRAINT ck_item_month CHECK (DAYOFMONTH(billing_month) = 1),
    CONSTRAINT ck_item_amounts CHECK (principal_amount >= 0 AND (fee_amount IS NULL OR fee_amount >= 0) AND ((fee_amount IS NULL AND billed_amount IS NULL) OR (fee_amount IS NOT NULL AND billed_amount IS NOT NULL AND billed_amount = principal_amount + fee_amount))),
    CONSTRAINT ck_item_rate CHECK (annual_fee_rate IS NULL OR annual_fee_rate BETWEEN 0 AND 1),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각',
    updated_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 수정 시각',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'JPA 낙관적 락 버전',
    CONSTRAINT ck_bill_item_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='일시불·할부 회차 청구';

CREATE TABLE refund (
    refund_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '환급 번호',
    payment_transaction_id BIGINT NOT NULL COMMENT '취소된 원거래',
    bill_item_id BIGINT NOT NULL COMMENT '환급 청구 회차; 일시불도 필수',
    user_id BIGINT NOT NULL COMMENT '환급 대상 사용자',
    linked_account_id BIGINT NULL COMMENT '환급 계좌; 처리 전 확정 필요',
    request_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '서버 생성 환급 작업 UUID; 재시도 유지',
    principal_amount BIGINT NOT NULL COMMENT '환급 원금',
    fee_amount BIGINT NOT NULL COMMENT '카드사 기준 환급 수수료; 확정값만 기록',
    refund_amount BIGINT NOT NULL COMMENT '확정 총 환급액',
    due_date DATE NULL COMMENT '한국 업무 날짜 환급 기한',
    status VARCHAR(24) NOT NULL COMMENT '환급 처리 상태 코드',
    completed_at TIMESTAMP(6) NULL COMMENT 'UTC 환급 성공 확인 시각',
    fin_request_no CHAR(20) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '은행 환급 입금 institutionTransactionUniqueNo; YYYYMMDD+HHMMSS+일련번호 6자리; 서버 공통 Redis INCR 채번, 금융망 새 호출마다 새 번호',
    fin_transaction_no VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '확인한 은행 입금 거래 참조',
    PRIMARY KEY (refund_id),
    UNIQUE KEY uk_refund_item (bill_item_id),
    UNIQUE KEY uk_refund_request (request_key),
    KEY ix_refund_item_payment_owner (bill_item_id, payment_transaction_id, user_id),
    KEY ix_refund_account_owner (linked_account_id, user_id),
    KEY ix_refund_due (status, due_date),
    CONSTRAINT fk_refund_item_owner FOREIGN KEY (bill_item_id, payment_transaction_id, user_id) REFERENCES bill_item (bill_item_id, payment_transaction_id, user_id),
    CONSTRAINT fk_refund_account_owner FOREIGN KEY (linked_account_id, user_id) REFERENCES linked_account (linked_account_id, user_id),
    CONSTRAINT ck_refund_amounts CHECK (principal_amount >= 0 AND fee_amount >= 0 AND refund_amount > 0 AND refund_amount = principal_amount + fee_amount),
    CONSTRAINT ck_refund_completed CHECK (completed_at IS NULL OR linked_account_id IS NOT NULL),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각',
    updated_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 수정 시각',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'JPA 낙관적 락 버전',
    CONSTRAINT ck_refund_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='청구 회차별 환급';

CREATE TABLE cashflow_item (
    cashflow_item_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '예정 내역 번호',
    user_id BIGINT NOT NULL COMMENT '내역 소유 사용자',
    linked_account_id BIGINT NULL COMMENT '예정 계좌; 미지정 가능',
    title VARCHAR(150) NOT NULL COMMENT '예정 내역 이름',
    direction VARCHAR(16) NOT NULL COMMENT 'INCOME / EXPENSE',
    amount BIGINT NOT NULL COMMENT '예정 원화 금액; 양수',
    scheduled_date DATE NOT NULL COMMENT '한국 기준 예정 날짜',
    recurrence_type VARCHAR(16) NOT NULL COMMENT 'NONE / DAILY / WEEKLY / MONTHLY / YEARLY',
    recurrence_end_date DATE NULL COMMENT '한국 기준 반복 종료일',
    status VARCHAR(24) NOT NULL COMMENT '예정 내역 상태 코드',
    memo VARCHAR(500) NULL COMMENT '사용자 메모; 민감정보 입력 주의',
    PRIMARY KEY (cashflow_item_id),
    KEY ix_cashflow_owner_date (user_id, scheduled_date),
    KEY ix_cashflow_account_owner (linked_account_id, user_id),
    CONSTRAINT fk_cashflow_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT fk_cashflow_account_owner FOREIGN KEY (linked_account_id, user_id) REFERENCES linked_account (linked_account_id, user_id),
    CONSTRAINT ck_cashflow_direction CHECK (direction IN ('INCOME','EXPENSE')),
    CONSTRAINT ck_cashflow_amount CHECK (amount > 0),
    CONSTRAINT ck_cashflow_recurrence CHECK (recurrence_type IN ('NONE','DAILY','WEEKLY','MONTHLY','YEARLY')),
    CONSTRAINT ck_cashflow_end CHECK (recurrence_end_date IS NULL OR recurrence_end_date >= scheduled_date),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각',
    updated_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 수정 시각',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'JPA 낙관적 락 버전',
    CONSTRAINT ck_cashflow_item_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='직접 입력한 예정 수입·지출';

