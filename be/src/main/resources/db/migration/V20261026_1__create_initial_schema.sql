-- S15P31E103-101: 23-table initial schema, MySQL 8.0.16+ / InnoDB.
-- All event timestamps are TIMESTAMP(6); application AND connection time zones must be UTC.
-- Monetary amounts are signed BIGINT KRW; exact ratios are DECIMAL.
-- No rates, retention periods, session lifetimes, or unknown settings are seeded here.
-- User settings follow the notification/forecast APIs; no assumed legacy three-column layout.
-- FK actions use InnoDB defaults (RESTRICT); no deletes, IF NOT EXISTS, or FK disabling.

CREATE TABLE app_user (
    user_id BIGINT NOT NULL AUTO_INCREMENT COMMENT 'YAMU 사용자 번호',
    name VARCHAR(100) NULL COMMENT '본인인증 이름; 가입 진행 중 미확보 가능',
    birth_date DATE NULL COMMENT '본인인증 생년월일',
    phone_enc VARBINARY(2048) NULL COMMENT '정규화한 휴대폰 번호의 암호화 봉투',
    phone_hash BINARY(32) NULL COMMENT '휴대폰 조회용 keyed HMAC-SHA-256; 정규화 후 계산',
    pin_hash VARCHAR(255) NULL COMMENT '솔트 포함 PIN 비밀번호 해시; 원문 금지',
    pin_updated_at TIMESTAMP(6) NULL COMMENT 'UTC 마지막 PIN 설정·변경 시각',
    identity_verified_at TIMESTAMP(6) NULL COMMENT 'UTC 본인인증 완료 시각',
    ssafy_member_id VARCHAR(255) NULL COMMENT '서버 생성 금융망 userId; yamu-{UUID}@yamu.com, 최초 생성 후 재사용, 메일 인증 없음',
    ssafy_user_key VARBINARY(2048) NULL COMMENT '금융망 userKey 암호화 봉투; 평문 금지',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING / ACTIVE / WITHDRAWN',
    deleted_at TIMESTAMP(6) NULL COMMENT 'UTC 탈퇴 시각; 실제 개인정보 파기와 별개',
    notification_settings JSON NULL COMMENT '알림 API의 유형별 설정; 미설정 NULL, 구조는 서비스 검증',
    forecast_settings JSON NULL COMMENT '잔고예보 API 설정; 미설정 NULL, 계좌·수입 참조는 서비스에서 소유권 검증',
    PRIMARY KEY (user_id),
    UNIQUE KEY uk_user_phone_birth (phone_hash, birth_date),
    UNIQUE KEY uk_user_ssafy_member (ssafy_member_id),
    CONSTRAINT ck_user_status CHECK (status IN ('PENDING','ACTIVE','WITHDRAWN')),
    CONSTRAINT ck_user_active CHECK (status <> 'ACTIVE' OR (name IS NOT NULL AND birth_date IS NOT NULL AND phone_enc IS NOT NULL AND phone_hash IS NOT NULL AND pin_hash IS NOT NULL AND pin_updated_at IS NOT NULL AND identity_verified_at IS NOT NULL)),
    CONSTRAINT ck_user_withdrawn CHECK ((status = 'WITHDRAWN' AND deleted_at IS NOT NULL) OR (status <> 'WITHDRAWN' AND deleted_at IS NULL)),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각',
    updated_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 수정 시각',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'JPA 낙관적 락 버전',
    CONSTRAINT ck_app_user_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='사용자';

CREATE TABLE user_device (
    user_device_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '등록 기기 번호',
    user_id BIGINT NOT NULL COMMENT '기기 소유 사용자',
    device_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '기기 등록 UUID',
    device_name VARCHAR(100) NULL COMMENT '사용자에게 표시할 기기명',
    platform VARCHAR(20) NOT NULL COMMENT '기기 운영체제; 현재 Android만 지원하므로 ANDROID 저장',
    public_key TEXT NULL COMMENT '현재 서명 검증용 공개키; PIN 전용 기기는 NULL 가능',
    key_algorithm VARCHAR(32) NULL COMMENT '공개키 알고리즘; 공개키와 함께 설정',
    biometric_enabled BOOLEAN NOT NULL DEFAULT FALSE COMMENT '생체인증 사용 동의·설정',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE / LOCKED / REVOKED',
    failed_count INT NOT NULL DEFAULT 0 COMMENT '연속 인증 실패 횟수',
    locked_until TIMESTAMP(6) NULL COMMENT 'UTC 잠금 해제 예정 시각',
    last_verified_at TIMESTAMP(6) NULL COMMENT 'UTC 마지막 인증 성공 시각',
    PRIMARY KEY (user_device_id),
    UNIQUE KEY uk_device_owner_uuid (user_id, device_uuid),
    UNIQUE KEY uk_device_owner (user_device_id, user_id),
    CONSTRAINT fk_device_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_device_status CHECK (status IN ('ACTIVE','LOCKED','REVOKED')),
    CONSTRAINT ck_device_failed CHECK (failed_count >= 0),
    CONSTRAINT ck_device_biometric CHECK (biometric_enabled IN (0,1) AND (biometric_enabled = 0 OR (public_key IS NOT NULL AND key_algorithm IS NOT NULL))),
    CONSTRAINT ck_device_key_pair CHECK ((public_key IS NULL AND key_algorithm IS NULL) OR (public_key IS NOT NULL AND key_algorithm IS NOT NULL)),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각',
    updated_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 수정 시각',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'JPA 낙관적 락 버전',
    CONSTRAINT ck_user_device_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='등록 기기';

CREATE TABLE user_device_event (
    user_device_event_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '기기 이벤트 번호',
    user_device_id BIGINT NOT NULL COMMENT '이벤트 대상 기기',
