CREATE TABLE card_benefit (
    card_benefit_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '혜택 정책 버전 번호',
    card_product_id BIGINT NOT NULL COMMENT '대상 상품',
    benefit_code VARCHAR(64) NOT NULL COMMENT '버전 간 유지되는 YAMU 논리 혜택 코드',
    policy_version SMALLINT NOT NULL COMMENT '정책 버전 1~32767; JPA 락 버전과 별개',
    benefit_name VARCHAR(150) NOT NULL COMMENT '혜택 이름',
    benefit_type VARCHAR(16) NOT NULL COMMENT 'DISCOUNT / CASHBACK / POINT',
    calculation_type VARCHAR(16) NOT NULL COMMENT 'RATE / FIXED',
    rate DECIMAL(9,6) NULL COMMENT '0~1 비율; RATE일 때 필수',
    fixed_value DECIMAL(19,6) NULL COMMENT '정액 혜택값; 원화 또는 포인트',
    value_unit VARCHAR(16) NOT NULL COMMENT 'KRW / POINT',
    point_krw_rate DECIMAL(19,6) NULL COMMENT '공식 포인트 원화 환산율; 미확인 NULL',
    application_timing VARCHAR(32) NULL COMMENT 'AT_APPROVAL: 승인 시 즉시 할인 / AT_BILLING: 청구 시 할인 / AFTER_BILLING: 청구 후 캐시백 / POINT_ACCRUAL: 포인트 적립; 미확인 NULL',
    rounding_mode VARCHAR(16) NULL COMMENT 'DOWN / HALF_UP / HALF_EVEN / UP; 약관 미확인 NULL',
    rounding_unit SMALLINT NULL COMMENT '절사·반올림 결과 단위; 1이면 1원 또는 1포인트, 미확인 NULL',
    rounding_stage VARCHAR(32) NULL COMMENT 'PER_TRANSACTION: 거래별 소수점 처리 / AFTER_AGGREGATION: 합산 후 소수점 처리; 미확인 NULL',
    min_payment_amount BIGINT NOT NULL DEFAULT 0 COMMENT '최소 결제 금액',
    min_performance_amount BIGINT NOT NULL DEFAULT 0 COMMENT '최소 전월 실적',
    valid_from DATE NULL COMMENT '공식 적용 시작일; 한국 날짜, 포함, 미확인 NULL',
    valid_until DATE NULL COMMENT '공식 적용 종료일; 한국 날짜, 미포함, 종료일 미확인·미정 NULL',
    conditions_json JSON NULL COMMENT '허용 키 weekdays/startTime/endTime; 한국 시각, 시작 포함·끝 미포함, 자정 넘김 지원; 구조·계산은 서비스 검증',
    terms_url VARCHAR(1000) NULL COMMENT '이 버전의 원본 약관',
    PRIMARY KEY (card_benefit_id),
    UNIQUE KEY uk_benefit_version (card_product_id, benefit_code, policy_version),
    UNIQUE KEY uk_benefit_product (card_benefit_id, card_product_id),
    KEY ix_benefit_effective (card_product_id, valid_from, valid_until),
    CONSTRAINT fk_benefit_product FOREIGN KEY (card_product_id) REFERENCES card_product (card_product_id),
    CONSTRAINT ck_benefit_version CHECK (policy_version > 0),
    CONSTRAINT ck_benefit_type CHECK (benefit_type IN ('DISCOUNT','CASHBACK','POINT')),
    CONSTRAINT ck_benefit_calc CHECK ((calculation_type = 'RATE' AND rate IS NOT NULL AND rate BETWEEN 0 AND 1 AND fixed_value IS NULL) OR (calculation_type = 'FIXED' AND fixed_value IS NOT NULL AND fixed_value >= 0 AND rate IS NULL)),
    CONSTRAINT ck_benefit_unit CHECK (value_unit IN ('KRW','POINT')),
    CONSTRAINT ck_benefit_exchange CHECK (point_krw_rate IS NULL OR point_krw_rate > 0),
    CONSTRAINT ck_benefit_rounding CHECK (rounding_mode IS NULL OR rounding_mode IN ('DOWN','HALF_UP','HALF_EVEN','UP')),
    CONSTRAINT ck_benefit_rounding_unit CHECK (rounding_unit IS NULL OR rounding_unit > 0),
    CONSTRAINT ck_benefit_rounding_stage CHECK (rounding_stage IS NULL OR rounding_stage IN ('PER_TRANSACTION','AFTER_AGGREGATION')),
    CONSTRAINT ck_benefit_amounts CHECK (min_payment_amount >= 0 AND min_performance_amount >= 0),
    CONSTRAINT ck_benefit_dates CHECK (valid_from IS NULL OR valid_until IS NULL OR valid_until > valid_from),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='혜택 정책 버전';

CREATE TABLE limit_group (
    limit_group_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '한도 그룹 버전 번호',
    card_product_id BIGINT NOT NULL COMMENT '대상 상품',
    group_code VARCHAR(64) NOT NULL COMMENT '상품 내 한도 규칙 식별 코드; 영문 대문자·밑줄(예: LIFE_SHARED), 버전 간 유지, 금액·버전 번호 제외',
    policy_version SMALLINT NOT NULL COMMENT '한도 정책 버전 1~32767',
    group_name VARCHAR(150) NOT NULL COMMENT '공유 한도 이름',
    period_type VARCHAR(16) NOT NULL COMMENT 'PER_TRANSACTION / DAILY / MONTHLY',
    limit_unit VARCHAR(16) NOT NULL COMMENT 'AMOUNT / COUNT',
    base_limit_value BIGINT NULL COMMENT '기본 한도; 실적 구간별 값만 있으면 NULL',
    valid_from DATE NULL COMMENT '한도 규칙의 공식 적용 시작일; 한국 날짜, 포함, 미확인 NULL',
    valid_until DATE NULL COMMENT '한도 규칙의 공식 적용 종료일; 한국 날짜, 미포함, 종료일 미확인·미정 NULL',
    PRIMARY KEY (limit_group_id),
    UNIQUE KEY uk_limit_version (card_product_id, group_code, policy_version),
    UNIQUE KEY uk_limit_product (limit_group_id, card_product_id),
    CONSTRAINT fk_limit_product FOREIGN KEY (card_product_id) REFERENCES card_product (card_product_id),
    CONSTRAINT ck_limit_version CHECK (policy_version > 0),
    CONSTRAINT ck_limit_period CHECK (period_type IN ('PER_TRANSACTION','DAILY','MONTHLY')),
    CONSTRAINT ck_limit_unit CHECK (limit_unit IN ('AMOUNT','COUNT')),
    CONSTRAINT ck_limit_value CHECK (base_limit_value IS NULL OR base_limit_value >= 0),
