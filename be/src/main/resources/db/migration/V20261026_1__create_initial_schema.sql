    KEY ix_device_event_time (user_device_id, created_at),
    CONSTRAINT fk_device_event_device FOREIGN KEY (user_device_id) REFERENCES user_device (user_device_id),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='기기 변경 이력';

CREATE TABLE step_up_audit_log (
    step_up_audit_log_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '인증 기록 번호',
    user_id BIGINT NOT NULL COMMENT '인증 사용자',
    user_device_id BIGINT NOT NULL COMMENT '인증 기기; 필수',
    auth_method VARCHAR(16) NOT NULL COMMENT 'PIN / BIOMETRIC',
    purpose VARCHAR(32) NOT NULL COMMENT 'LOGIN / APP_UNLOCK / BARCODE / ACCOUNT_LINK 등; 인증 명세 코드',
    result VARCHAR(16) NOT NULL COMMENT 'SUCCESS / FAILURE',
    fail_reason VARCHAR(100) NULL COMMENT '원문 없이 저장하는 실패 코드',
    challenge_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '추적 식별자; challenge 원문 아님',
    ip_address VARCHAR(45) CHARACTER SET ascii NULL COMMENT 'IPv4 또는 IPv6 문자열',
    user_agent VARCHAR(512) NULL COMMENT '민감값을 제거한 요청 클라이언트 정보',
    PRIMARY KEY (step_up_audit_log_id),
    UNIQUE KEY uk_audit_owner (step_up_audit_log_id, user_id),
    KEY ix_audit_user_time (user_id, created_at),
    KEY ix_audit_device_owner (user_device_id, user_id),
    CONSTRAINT fk_audit_device_owner FOREIGN KEY (user_device_id, user_id) REFERENCES user_device (user_device_id, user_id),
    CONSTRAINT ck_audit_method CHECK (auth_method IN ('PIN','BIOMETRIC')),
    CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS','FAILURE')),
    CONSTRAINT ck_audit_failure CHECK (result <> 'SUCCESS' OR fail_reason IS NULL),
    created_at TIMESTAMP(6) NOT NULL COMMENT 'UTC 생성 시각'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='추가 인증 이력';

