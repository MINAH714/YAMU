"""Generate the explicit card-image update SQL. Standard library only; never connects to a DB."""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEY = re.compile(r"cards/[A-Za-z0-9_./-]+")
SHA256 = re.compile(r"[0-9a-f]{64}")
STATES = {"APPLY", "HOLD", "EXCLUDED"}


def validate(document):
    cards = document["cards"]
    ids, products = set(), set()
    for card in cards:
        identity = tuple(card[name] for name in ("issuer_code", "product_name", "card_type"))
        if not all(isinstance(value, str) and value.strip() == value and value for value in identity):
            raise ValueError("상품 식별값이 비어 있거나 공백이 포함되어 있습니다.")
        if card["card_id"] in ids or identity in products:
            raise ValueError("수집 ID 또는 상품 식별값이 중복됩니다.")
        ids.add(card["card_id"])
        products.add(identity)
        if card["card_type"] not in {"CREDIT", "CHECK"} or card["state"] not in STATES:
            raise ValueError("카드 종류 또는 적용 상태가 잘못되었습니다.")
        key = card["image_key"]
        if (len(key) > 1024 or not KEY.fullmatch(key)
                or any(part in {"", ".", ".."} for part in key.split("/"))
                or not key.startswith("cards/" + card["card_id"] + "/")):
            raise ValueError("상품과 일치하는 안전한 이미지 객체 키가 필요합니다.")
        if not SHA256.fullmatch(card["sha256"]) or key.rsplit("/", 1)[-1].split(".")[0] != card["sha256"]:
            raise ValueError("이미지 키와 SHA-256이 일치하지 않습니다.")
        if card["content_type"] not in {"image/png", "image/jpeg", "image/webp"} or card["frames"] != 1:
            raise ValueError("정적 카드 앞면 이미지만 사용할 수 있습니다.")
        if card["state"] != "APPLY" and not card.get("reason"):
            raise ValueError("보류·제외 사유가 필요합니다.")
        if card["card_id"] == "samsung-aap1767" and (
                "/static-front/" not in key or not key.endswith(".png")):
            raise ValueError("삼성 iD SIMPLE은 검증된 정적 앞면 PNG를 사용해야 합니다.")
    return sorted(cards, key=lambda card: card["card_id"])


def quote(value):
    # Reject backslashes rather than relying on the current MySQL NO_BACKSLASH_ESCAPES setting.
    if "\\" in value or any(ord(c) < 32 for c in value):
        raise ValueError("SQL 문자열에 제어 문자나 역슬래시를 사용할 수 없습니다.")
    return "'" + value.replace("'", "''") + "'"


def render_sql(document):
    cards = [card for card in validate(document) if card["state"] == "APPLY"]
    if not cards:
        raise ValueError("적용 대상 카드가 없습니다.")
    rows = ",\n".join("    (" + ", ".join(quote(card[key]) for key in
                      ("card_id", "issuer_code", "product_name", "card_type", "image_key")) + ")" for card in cards)
    return """-- S15P31E103-244. Generated by card-images/build_image_seed.py; do not edit by hand.
-- Requires MR !75 / V20261102_2. Run explicitly in the selected schema; stop on SQL errors.
-- Updates NULL image keys only. Does not create products or alter benefits, users or account data.
SELECT DATABASE() AS selected_database;
SELECT image_key FROM card_product LIMIT 0;
DROP TEMPORARY TABLE IF EXISTS tmp_yamu244_card_images;
CREATE TEMPORARY TABLE tmp_yamu244_card_images (
    card_id VARCHAR(100) NOT NULL,
    issuer_code VARCHAR(32) NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    card_type VARCHAR(16) NOT NULL,
    image_key VARCHAR(1024) NOT NULL,
    PRIMARY KEY (issuer_code, product_name, card_type)
);
INSERT INTO tmp_yamu244_card_images (card_id, issuer_code, product_name, card_type, image_key) VALUES
""" + rows + ";\n" + """
START TRANSACTION;
-- Preflight: missing products are expected when only the three representative cards are installed.
SELECT i.card_id, i.issuer_code, i.product_name, i.card_type, p.card_product_id,
       CASE WHEN p.card_product_id IS NULL THEN 'MISSING_PRODUCT'
            WHEN p.image_key IS NULL THEN 'WILL_SET'
            WHEN BINARY p.image_key = BINARY i.image_key THEN 'ALREADY_MATCHED'
            ELSE 'CONFLICT_EXISTING_KEY' END AS mapping_status,
       p.image_key AS existing_image_key, i.image_key AS expected_image_key
FROM tmp_yamu244_card_images i LEFT JOIN card_product p
  ON BINARY p.issuer_code = BINARY i.issuer_code
 AND BINARY p.product_name = BINARY i.product_name AND BINARY p.card_type = BINARY i.card_type
ORDER BY i.card_id;

UPDATE card_product p JOIN tmp_yamu244_card_images i
  ON BINARY p.issuer_code = BINARY i.issuer_code
 AND BINARY p.product_name = BINARY i.product_name AND BINARY p.card_type = BINARY i.card_type
SET p.image_key = i.image_key
WHERE p.image_key IS NULL;
SELECT ROW_COUNT() AS updated_image_count;

SELECT i.card_id, p.card_product_id,
       CASE WHEN p.card_product_id IS NULL THEN 'MISSING_PRODUCT'
            WHEN BINARY p.image_key = BINARY i.image_key THEN 'MATCHED'
            ELSE 'CONFLICT_EXISTING_KEY' END AS final_status
FROM tmp_yamu244_card_images i LEFT JOIN card_product p
  ON BINARY p.issuer_code = BINARY i.issuer_code
 AND BINARY p.product_name = BINARY i.product_name AND BINARY p.card_type = BINARY i.card_type
ORDER BY i.card_id;
COMMIT;
DROP TEMPORARY TABLE tmp_yamu244_card_images;
"""


def render_report(document):
    cards = validate(document)
    lines = ["# 카드 이미지 매핑 확인 결과", "",
             "기준: 기존 상품의 `issuer_code + product_name + card_type`. 실제 DB 조회 결과가 아닌 정적 대조 자료다.",
             "수집 ID는 자료 연결용이며 RDS PK로 사용하지 않는다. SQL은 기존 상품의 NULL 이미지에만 적용한다.", "",
             "| 적용 상태 | 카드 수 |", "|---|---:|"]
    lines += [f"| {state} | {sum(c['state'] == state for c in cards)} |" for state in ("APPLY", "HOLD", "EXCLUDED")]
    lines += ["", "## 상품별 대조", "", "| 수집 ID | DB 카드사 | DB 상품명 | 종류 | 상태 | 확인 사항 |",
              "|---|---|---|---|---|---|"]
    for c in cards:
        notes = c.get("reason") or ("원문 상품명과 DB 상품명 표기가 달라 기존 Seed 이름에 명시 매핑"
                    if c["source_product_name"] != c["product_name"] else "기존 Seed 상품명과 일치")
        lines.append(f"| {c['card_id']} | {c['issuer_code']} | {c['product_name']} | {c['card_type']} | {c['state']} | {notes} |")
    lines += ["", "## 적용 시 확인할 항목", "",
              "- MR !75의 image_key 컬럼이 먼저 필요하다. 이번 SQL에는 스키마 변경이 없다.",
              "- 대표 3종만 있는 DB: 3개 매핑, 나머지 14개 MISSING_PRODUCT. 추가 상품을 만들지 않는다.",
              "- 기존 17종이 있는 DB: 17개 매핑. 보류 1종·제외 2종은 SQL에 포함하지 않는다.",
              "- 이미 같은 키가 있으면 재실행 변경 0건. 다른 키·빈 문자열은 보존하고 충돌로 보고한다.",
              "- 가맹점·혜택·사용자 데이터와 상품의 다른 컬럼은 갱신하지 않는다.",
              "- 현재 RDS의 존재 상품·기존 이미지 충돌 여부는 미확인이다. 적용 담당자가 SQL의 사전/사후 결과를 확인한다.", ""]
    return "\n".join(lines)


def main():
    document = json.loads((HERE / "card-images.json").read_text(encoding="utf-8"))
    (HERE.parent / "03-card-product-images.sql").write_text(render_sql(document), encoding="utf-8", newline="\n")
    (HERE / "report.md").write_text(render_report(document), encoding="utf-8", newline="\n")
    print("Generated image SQL and report; no database connection was made.")


if __name__ == "__main__":
    main()
